function applyCraftL10n() {
  const p = path.join(ROOT, "craft/october/stages.json");
  const spec = JSON.parse(fs.readFileSync(p, "utf8"));
  const enBase = spec.uiCopy.en;

  for (const lang of LANGS) {
    const overlay = CRAFT_UI[lang] || {};
    spec.uiCopy[lang] = { ...enBase, ...(spec.uiCopy[lang] || {}), ...overlay };
  }

  for (const stage of spec.stages) {
    const enLines = stage.lines?.en;
    const koLines = stage.lines?.ko;
    const map = STAGE_LINES[stage.key];
    if (!enLines || !map) continue;
    stage.lines = stage.lines || {};
    for (const lang of LANGS) {
      if (lang === "en") stage.lines.en = enLines;
      else if (lang === "ko" && koLines) stage.lines.ko = koLines;
      else if (map[lang]) stage.lines[lang] = map[lang];
      else stage.lines[lang] = map.es || enLines;
    }
  }

  fs.writeFileSync(p, JSON.stringify(spec, null, 2) + "\n");
  console.log("Applied craft uiCopy + stage lines for", LANGS.length, "languages.");
}

applyCraftL10n();
